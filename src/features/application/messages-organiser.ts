/** "14 Nov, 12:40" in Helsinki time, in the page's language. */
export function formatWhen(iso: string, lang: UiLang): string {
  return new Intl.DateTimeFormat(UI_LANG_LOCALES[lang], {
    day: "numeric",
    month: "short",
    hour: "2-digit",
    minute: "2-digit",
    timeZone: "Europe/Helsinki",
  }).format(new Date(iso));
}

/** Ask-to-meet error codes as lines. */
export function meetErrorLine(m: (typeof rankedMessages)["en"], code: string | null): string {
  if (code === "already_requested") return m.errAlreadyRequested;
  if (code === "not_available") return m.errNotAvailable;
  if (code === "unknown_link") return m.errUnknownLink;
  return m.errGeneric;
}

/** A move's inputs checked before anything is sent. Null when fine. */
export function moveProblem(m: (typeof rankedMessages)["en"], position: string, reason: string): string | null {
  const n = Number(position);
  if (!position.trim() || !Number.isInteger(n) || n < 1) return m.moveNeedPosition;
  if (reason.trim().length < 3) return m.moveNeedReason;
  return null;
}
